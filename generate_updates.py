#!/usr/bin/env python3
"""Generate a local Bash script to run updates over SSH."""

import argparse
import csv
import json
import re
import shlex
import sys
from pathlib import Path

DESTINATION_RE = re.compile(r"^[^\s@]+@[^\s@]+$")


def parse_tag_ids(value):
    """Return tag IDs from a list or JSON-encoded list; otherwise None."""
    if isinstance(value, list):
        tags = value
    elif isinstance(value, str):
        try:
            tags = json.loads(value)
        except json.JSONDecodeError:
            return None
    else:
        return None
    return tags if isinstance(tags, list) else None


def parse_ssh_command(ssh1_string):
    """Parse and safely reconstruct the complete ssh1String invocation."""
    if not isinstance(ssh1_string, str) or not ssh1_string.strip():
        return None
    try:
        tokens = shlex.split(ssh1_string)
    except ValueError:
        return None
    if not tokens or not any(DESTINATION_RE.fullmatch(token) for token in tokens):
        return None
    return shlex.join(tokens)


def inventory_records(path):
    """Yield inventory records, decoding JSON payloads when present."""
    with path.open(encoding="utf-8-sig", newline="") as source:
        reader = csv.DictReader(source)
        if not reader.fieldnames:
            raise ValueError("Le CSV est vide ou ne contient pas d’en-tête.")
        for line_number, row in enumerate(reader, start=2):
            if "payload" in row:
                try:
                    record = json.loads(row["payload"] or "")
                except json.JSONDecodeError as exc:
                    raise ValueError(f"JSON invalide dans payload à la ligne {line_number}.") from exc
                if not isinstance(record, dict):
                    raise ValueError(f"payload doit être un objet JSON à la ligne {line_number}.")
                yield record
            else:
                yield row


def commands_from_inventory(path):
    commands = []
    skipped = 0
    for record in inventory_records(path):
        tags = parse_tag_ids(record.get("tagIds"))
        if tags is None or 6 not in tags:
            continue
        command = parse_ssh_command(record.get("ssh1String"))
        if command is None:
            skipped += 1
            continue
        if command not in commands:
            commands.append(command)
    return commands, skipped


def generate_script(commands, remote_command):
    lines = [
        "#!/usr/bin/env bash",
        "",
        "# Generated by generate_updates.py; review before execution.",
        "set -Eeuo pipefail",
        "trap 'status=$?; printf \"ERREUR : échec à la ligne %s (code %s)\\n\" \"$LINENO\" \"$status\" >&2; exit \"$status\"' ERR",
        "set -x",
        "shopt -s expand_aliases",
        'alias sshg=\'ssh -A -o SendEnv="GIT*"\'',
        "",
    ]
    for command in commands:
        lines.append(f"{command} {shlex.quote(remote_command)}")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Génère start-updates.sh pour les serveurs SSH de l’inventaire.")
    parser.add_argument("inventory", help="chemin du fichier CSV d’inventaire")
    parser.add_argument("remote_command", help="commande shell à exécuter sur les serveurs (chemin de script ou commande inline)")
    args = parser.parse_args(argv)

    inventory = Path(args.inventory)
    if not inventory.is_file():
        parser.error(f"fichier d’inventaire introuvable : {inventory}")
    if not args.remote_command.strip() or "\n" in args.remote_command or "\r" in args.remote_command or "\0" in args.remote_command:
        parser.error("la commande distante doit être non vide et tenir sur une seule ligne")

    try:
        commands, skipped = commands_from_inventory(inventory)
        Path("start-updates.sh").write_text(generate_script(commands, args.remote_command), encoding="utf-8")
        Path("start-updates.sh").chmod(0o755)
    except (OSError, ValueError, csv.Error) as exc:
        print(f"Erreur : {exc}", file=sys.stderr)
        return 1

    print(f"Script généré : start-updates.sh ({len(commands)} commande(s) SSH).")
    if skipped:
        print(f"{skipped} enregistrement(s) tagué(s) 6 ignoré(s) : ssh1String absent ou destination invalide.")
    print("Le script Bash n’a pas été exécuté.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
